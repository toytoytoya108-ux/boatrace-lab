"""地方競馬（NAR）の単勝・複勝の市場を、競艇と同じ物差しで測る。

事前登録は `reports/research/nar_plan.md`（データを見る前に書いた）。
2026年3月以降しかオッズが無く、**3〜5月は探索期間**。確認（6月以降）は1回だけ評価する。

物差し: 100円均等、払戻は公式の確定配当。`比 = 実勝率 ÷ 市場確率`。
市場確率 q = レース内で正規化した 1/確定単勝オッズ。帰無（市場が正しい）なら回収率＝実測払戻率。

出力: reports/research/nar_market.md
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from boatlab.research.nar import RATE, load_month, roi_ci  # noqa: E402

D = Path("data/nar")
OUT = Path("reports/research/nar_market.md")


def line(r, name, extra=""):
    roi, lo, hi = r
    return f"{roi*100:.1f}% | {lo*100:.0f}〜{hi*100:.0f}%"


def bet(df, pay_col, mask=None, seed=0):
    d = df if mask is None else df[mask]
    pay = d[pay_col].values.astype(float)
    stake = np.full(len(pay), 100.0)
    roi, lo, hi = roi_ci(stake, pay, seed=seed)
    hit = (pay > 0).mean() if len(pay) else np.nan
    return dict(n=len(pay), hit=hit, roi=roi, lo=lo, hi=hi,
                avg=pay[pay > 0].mean() if (pay > 0).any() else 0.0)


def main():
    months = sorted({p.name[:6] for p in D.glob("*_horselist.csv")})
    parts = [load_month(D, m) for m in months]
    df = pd.concat([p[0] for p in parts], ignore_index=True)
    S = 1.0 / df.groupby("race_id")["book_rate"].first().mean()   # Σ(1/オッズ) の平均＝必要比
    races = df.race_id.nunique()
    L = [f"# 地方競馬（NAR）の単勝・複勝を測る — {'・'.join(months)}（{races:,}レース・{len(df):,}頭）\n",
         "事前登録: `reports/research/nar_plan.md`。**この期間は探索（3〜5月）。確認は6月以降で1回だけ行う。**",
         "物差しは競艇と同じ: 100円均等、払戻は公式の確定配当、`比 = 実勝率 ÷ 市場確率`。\n",
         "## 0. データの検証（先に値を確かめる）\n",
         "- **オッズは確定オッズ**: 勝ち馬の `単勝オッズ × 100` と公式の単勝払戻金が **99.5%で完全一致**。",
         "  残り0.46%（6件）はすべて**同着**で払戻が分割されたレース。人気も払戻の人気と100%一致。",
         "- **取消の扱い**: 出走取消(71)・競走除外(36)は**オッズ行そのものが無い**（返還）ので母数から自動的に外れる。",
         "  競走中止(36)・失格(3)はオッズも人気もあり、馬券は外れになるので**負けとして残す**。",
         "  これを間違えて着順の無い馬を全部落とすと、レースによっては1番人気が消えて払戻率が124%に見える（実際に一度踏んだ）。",
         "- 欠測・非数値のオッズは **0件**。\n"]

    # ---- 1. 実測払戻率
    br = df.groupby("race_id")["book_rate"].first()
    L += ["## 1. 実測の払戻率（Σ(1/確定単勝オッズ) の逆数）\n",
          f"全体 **{br.mean()*100:.1f}%**（標準偏差 {br.std()*100:.2f}pt、範囲 {br.min()*100:.1f}〜{br.max()*100:.1f}%）。",
          f"公表は80%。**実測が {80-br.mean()*100:.1f}pt 低い**のは、オッズが0.1刻みで切り捨て表示されるため",
          "（表示オッズ ≤ 真のオッズ なので 1/オッズ の合計が1.25を超える）。",
          "",
          f"→ **必要比は 1.250 ではなく {S:.3f}**（= 1 ÷ 実測払戻率）。",
          f"競艇の単勝は同じ測り方で 73.6% ＝ 必要比 1.359 だったので、**地方競馬は {(1.359/S-1)*100:.1f}% 有利**。\n",
          "| 競馬場 | レース数 | 実測払戻率 |", "|---|---:|---:|"]
    for cj, g in df.groupby("競馬場"):
        b = g.groupby("race_id")["book_rate"].first()
        L.append(f"| {cj} | {len(b):,} | {b.mean()*100:.2f}% |")

    # ---- 2. 人気順別（favorite-longshot）
    L += ["\n## 2. 人気順ごとの単勝（favorite-longshot bias）\n",
          "**比 = 回収率 ÷ 実測払戻率。1.00なら市場は正しい。**\n",
          "| 人気 | 頭数 | 勝率 | 市場確率 | 比 | 平均オッズ | 単勝回収率 | 95%区間 |", "|---|---:|---:|---:|---:|---:|---:|---|"]
    for k in range(1, 13):
        m = df["pop"] == k
        if m.sum() < 100:
            continue
        r = bet(df, "win_pay", m, seed=k)
        q = df.loc[m, "q"].mean()
        L.append(f"| {k}番人気 | {r['n']:,} | {r['hit']*100:.1f}% | {q*100:.1f}% | "
                 f"{'**' if r['hit']/q>1 else ''}{r['hit']/q:.3f}{'**' if r['hit']/q>1 else ''} | "
                 f"{df.loc[m,'win_odds'].mean():.1f} | **{r['roi']*100:.1f}%** | {r['lo']*100:.0f}〜{r['hi']*100:.0f}% |")

    # ---- 3. オッズ帯別
    L += ["\n## 3. オッズ帯ごとの単勝\n",
          "| 確定オッズ | 頭数 | 勝率 | 市場確率 | 比 | 回収率 | 95%区間 |", "|---|---:|---:|---:|---:|---:|---|"]
    edges = [1.0, 1.5, 2.0, 3.0, 5.0, 8.0, 15.0, 30.0, 60.0, 150.0, 1e9]
    for lo_, hi_ in zip(edges[:-1], edges[1:]):
        m = (df["win_odds"] >= lo_) & (df["win_odds"] < hi_)
        if m.sum() < 100:
            continue
        r = bet(df, "win_pay", m, seed=int(lo_))
        q = df.loc[m, "q"].mean()
        lab = f"{lo_:g}〜{hi_:g}倍" if hi_ < 1e8 else f"{lo_:g}倍以上"
        L.append(f"| {lab} | {r['n']:,} | {r['hit']*100:.1f}% | {q*100:.1f}% | "
                 f"{'**' if r['hit']/q>1 else ''}{r['hit']/q:.3f}{'**' if r['hit']/q>1 else ''} | "
                 f"**{r['roi']*100:.1f}%** | {r['lo']*100:.0f}〜{r['hi']*100:.0f}% |")

    # ---- 4. 複勝
    L += ["\n## 4. 人気順ごとの複勝（実際の複勝払戻で採点）\n",
          "| 人気 | 頭数 | 複勝的中率 | 平均払戻 | 元返し率 | 複勝回収率 | 95%区間 |", "|---|---:|---:|---:|---:|---:|---|"]
    for k in range(1, 9):
        m = df["pop"] == k
        if m.sum() < 100:
            continue
        r = bet(df, "pla_pay", m, seed=100 + k)
        pp = df.loc[m, "pla_pay"]
        moto = (pp == 100).sum() / max((pp > 0).sum(), 1)
        L.append(f"| {k}番人気 | {r['n']:,} | {r['hit']*100:.1f}% | {r['avg']:,.0f}円 | {moto*100:.1f}% | "
                 f"**{r['roi']*100:.1f}%** | {r['lo']*100:.0f}〜{r['hi']*100:.0f}% |")

    # ---- 5. 絞り込み曲線（市場の確信度 = 1番人気の市場確率）
    top = df[df["q_rank"] == 1].copy()
    L += ["\n## 5. 市場が自信を持つレースだけに絞る（買うのは1番人気1点）\n",
          "レースを「1番人気の市場確率」の高い順に並べ、上位x%だけ買う。`sweet_spot.md` と同じ絵。\n",
          "| 絞り込み | レース数 | 単勝 的中率 | 単勝 回収率 | 95%区間 | 複勝 的中率 | 複勝 回収率 | 95%区間 |",
          "|---|---:|---:|---:|---|---:|---:|---|"]
    for frac in (1.0, 0.5, 0.3, 0.2, 0.1, 0.05, 0.02, 0.01):
        thr = top["q"].quantile(1 - frac)
        m = top["q"] >= thr
        w = bet(top, "win_pay", m, seed=int(frac * 1000))
        p = bet(top, "pla_pay", m, seed=int(frac * 1000) + 1)
        L.append(f"| 上位{frac*100:g}% | {w['n']:,} | {w['hit']*100:.1f}% | **{w['roi']*100:.1f}%** | "
                 f"{w['lo']*100:.0f}〜{w['hi']*100:.0f}% | {p['hit']*100:.1f}% | **{p['roi']*100:.1f}%** | "
                 f"{p['lo']*100:.0f}〜{p['hi']*100:.0f}% |")

    # ---- 6. 元返しの効き方
    pp = top["pla_pay"]
    L += ["\n### 元返し（100円下限）の効き方\n",
          f"1番人気の複勝で的中したうち **{(pp==100).sum()/max((pp>0).sum(),1)*100:.1f}%** が100円（元返し）。",
          "競艇の複勝上位10%では元返し77.7%で、そこが回収率99.1%の天井を作っていた。",
          "**元返しの割合が高いほど回収率は100%に近づくが、絶対に超えない**（`sweet_spot.md`）。\n"]

    # ---- 7. ばんえい vs 平地
    L += ["## 6. ばんえい（帯広）と平地の比較\n",
          "| 区分 | レース数 | 実測払戻率 | 1番人気 勝率 | 1番人気 単勝回収率 | 1番人気 複勝回収率 |", "|---|---:|---:|---:|---:|---:|"]
    for nm, m0 in (("ばんえい", df["banei"] == 1), ("平地", df["banei"] == 0)):
        g = df[m0]; t = g[g["q_rank"] == 1]
        b = g.groupby("race_id")["book_rate"].first()
        w = bet(t, "win_pay", seed=7); p = bet(t, "pla_pay", seed=8)
        L.append(f"| {nm} | {len(b):,} | {b.mean()*100:.2f}% | {w['hit']*100:.1f}% | {w['roi']*100:.1f}% | {p['roi']*100:.1f}% |")

    # ---- 8. 帰無シミュレーション（市場が正しい世界で同じ絞り込みをやる）
    rng = np.random.default_rng(3)
    NSIM = 200
    L += ["\n## 7. 帰無シミュレーション（市場が正しい世界で同じ表を作る）\n",
          f"各レースの勝ち馬を市場確率 q から引き直し、同じ「上位x%」の絞り込みで単勝回収率を出す。{NSIM}回。\n",
          "| 絞り込み | 実測 | 帰無 平均 | 帰無 範囲 | 実測以上が出た回数 |", "|---|---:|---:|---|---:|"]
    grp = [g for _, g in df.groupby("race_id", sort=False)]
    qs = [g["q"].values for g in grp]
    od = [g["win_odds"].values for g in grp]
    qtop = np.array([q.max() for q in qs])
    itop = np.array([int(np.argmax(q)) for q in qs])
    cum = [np.cumsum(q / q.sum()) for q in qs]
    sims = np.zeros((NSIM, len(grp)), bool)
    for si in range(NSIM):
        u = rng.random(len(grp))
        for i, c in enumerate(cum):
            sims[si, i] = (int(np.searchsorted(c, u[i])) == itop[i])
    for frac in (1.0, 0.3, 0.1, 0.05, 0.02):
        thr = np.quantile(qtop, 1 - frac)
        m = qtop >= thr
        real = bet(top, "win_pay", top["q"] >= top["q"].quantile(1 - frac), seed=9)["roi"]
        ii = np.flatnonzero(m)
        favod = np.array([od[i][itop[i]] for i in ii]) * 100.0
        vals = np.array([np.where(sims[si][m], favod, 0.0).sum() / (100.0 * m.sum()) for si in range(NSIM)])
        L.append(f"| 上位{frac*100:g}% | {real*100:.1f}% | {vals.mean()*100:.1f}% | "
                 f"{vals.min()*100:.1f}〜{vals.max()*100:.1f}% | {(vals>=real).sum()}/{NSIM} |")

    # ---- 9. 期間を半分に割って再現するか（3月のみのときは1〜15日 / 16〜31日）
    half = top["date"].dt.day <= 15
    L += ["\n## 8. 期間を半分に割ると同じ向きに出るか\n",
          "偶然の山を見ていないかの最低限の確認。**同じ向きに出ることが必要条件であって、十分条件ではない。**\n",
          "| 絞り込み | 前半 n | 前半 単勝 | 前半 複勝 | 後半 n | 後半 単勝 | 後半 複勝 |", "|---|---:|---:|---:|---:|---:|---:|"]
    for frac in (1.0, 0.3, 0.1, 0.05):
        cells = []
        for hm in (half, ~half):
            t2 = top[hm]
            thr = t2["q"].quantile(1 - frac)
            m2 = t2["q"] >= thr
            w = bet(t2, "win_pay", m2, seed=11); p = bet(t2, "pla_pay", m2, seed=12)
            cells += [f"{w['n']:,}", f"{w['roi']*100:.1f}%", f"{p['roi']*100:.1f}%"]
        L.append(f"| 上位{frac*100:g}% | " + " | ".join(cells) + " |")

    # ---- 10. 結論
    L += ["",
          "## 9. わかったこと（2026-03のみ・探索段階）",
          "",
          "### ① 実際の払戻率は80%ではなく78.6%",
          "オッズが0.1刻みで切り捨て表示されるぶん、胴元の取り分が1.4pt増える。**必要比は1.250ではなく1.272。**",
          "それでも競艇の単勝（同じ測り方で73.6%＝必要比1.359）より **6.8%有利**。ここは事前の見立てどおり。",
          "",
          "### ② 本命側の歪みは実在する。競艇と同じ向きで、絞るほど強くなる",
          "1番人気の単勝は 勝率44.5% に対し市場確率43.0%（比1.034）。オッズ1.0〜1.5倍の帯では 勝率73.0% 対 63.7%（**比1.147**）。",
          "「1番人気の市場確率」が高い順にレースを絞ると、単勝回収率は 81.7% →（上位10%）89.2% →（上位5%）**95.0%**、",
          "複勝は 89.2% →（上位10%）96.6% →（上位5%）**98.6%** と単調に上がる。",
          "帰無（市場が正しい世界で勝ち馬を引き直す）200回では、上位10%・上位5%とも実測以上が **0/200**。",
          "3月を前半・後半に割っても両方で同じ向き（上位5%の複勝 99.1% / 100.6%）。**歪みの存在自体は、ほぼ疑いがない。**",
          "",
          "### ③ それでも100%は超えない。理由は控除率ではなく『元返し』",
          "上位5%のレースで1番人気の確定オッズは **1.0〜1.1倍**。複勝の払戻は56/66が**ちょうど100円**。",
          "この領域では `回収率 ≒ 的中率 × (平均払戻/100)` で、平均払戻が100円に張り付くので **回収率は的中率で頭打ち**になる。",
          "上位5%の複勝的中率は 97.0%、単勝は 89.4%。→ 98.6% と 95.0%。**当たっても増えない領域に入っている。**",
          "",
          "**控除率が低いことは、この領域では何の役にも立たない。** 元返しの下限が効いている間、胴元は既に取り分を放棄しているからで、",
          "回収率を決めているのは払戻率ではなく『本命がどれだけ確実に来るか』だけになる。",
          "",
          "### ④ だから競艇の方が100%に近かった、という逆説",
          "| | 控除率 | 本命端の複勝 回収率 | 的中率 | 元返しの割合 |",
          "|---|---:|---:|---:|---:|",
          "| 競艇（複勝・市場確信度 上位10%） | 25% | **99.1%** | ほぼ99% | 77.7% |",
          "| 地方競馬（複勝・上位5%） | 20%（実測21.4%） | 98.6% | 97.0% | 85% |",
          "",
          "競艇の1号艇は「6艇中の1コース」という構造的な優位があり、上位10%のレースではほぼ確実に3着以内に来る。",
          "競馬の1番人気は、どれだけ市場が確信していても **3%前後は馬券圏外に飛ぶ**。",
          "**元返し領域での天井は控除率でなく的中率で決まるので、控除率5pt分の有利は回収されない。**",
          "",
          "### ⑤ 元返しの外側では、必要な歪みに 0.125 足りない",
          "配当が下限に張り付かない領域で最大の比は オッズ1.0〜1.5倍帯の **1.147**（n=282、回収率89.4%、区間84〜95%）。",
          "必要なのは 1.272。**必要な歪みの90%までは来ているが、残り10%が埋まらない。**",
          "競艇で測った頑健側の上限（crowd_bias 上位1%で1.139）とほとんど同じ数字であることに注意する。",
          "「市場は本命を1〜1.15倍だけ過小評価する」は、競技をまたいで再現する普遍的な大きさらしい。",
          "",
          "### 次にやること",
          "- 事前登録どおり、**4月・5月で探索を完成**させ、**6月以降を確認期間として1回だけ**評価する。",
          "- 決着する問いは1つだけ: **複勝・上位5%が 98.6% なのか 100%超なのか。**",
          "  現在 n=66（±4pt）。±0.7pt まで詰めるには約600レース＝**9〜10か月分**。オッズは2026年3月開始なので、年内いっぱいで決着する。",
          "- 上位5%は **1日2.1レース**（1か月66R）。仮に真値が100.7%でも、100円賭けて0.7円。**規模の問題は競艇と同じ。**",
          "- ここまではすべて**確定オッズ**の数字。締切前オッズでの再現は別途必要（競艇では買う帯で中央値−8%だった）。",
          ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
